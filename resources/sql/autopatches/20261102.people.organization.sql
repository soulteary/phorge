CREATE TABLE {$NAMESPACE}_user.organization_identityepoch (
  userPHID VARBINARY(64) NOT NULL PRIMARY KEY,
  epoch BIGINT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE {$NAMESPACE}_user.organization_unit (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  unitID VARBINARY(64) NOT NULL,
  kind VARBINARY(16) NOT NULL,
  state VARBINARY(16) NOT NULL,
  name VARCHAR(255) NOT NULL,
  parentID VARBINARY(64) DEFAULT NULL,
  version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY key_identity (unitID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE {$NAMESPACE}_user.organization_member (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  unitID VARBINARY(64) NOT NULL,
  userPHID VARBINARY(64) NOT NULL,
  state VARBINARY(16) NOT NULL,
  validFrom BIGINT UNSIGNED NOT NULL,
  validUntil BIGINT UNSIGNED DEFAULT NULL,
  version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY key_identity (unitID, userPHID)
) ENGINE=InnoDB;

CREATE TABLE {$NAMESPACE}_user.organization_appointment (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  unitID VARBINARY(64) NOT NULL,
  userPHID VARBINARY(64) NOT NULL,
  role VARBINARY(16) NOT NULL,
  state VARBINARY(16) NOT NULL,
  validFrom BIGINT UNSIGNED NOT NULL,
  validUntil BIGINT UNSIGNED DEFAULT NULL,
  version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY key_identity (unitID, userPHID)
) ENGINE=InnoDB;

CREATE TABLE {$NAMESPACE}_user.organization_primarydepartment (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  userPHID VARBINARY(64) NOT NULL,
  unitID VARBINARY(64) NOT NULL,
  version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  UNIQUE KEY key_identity (userPHID)
) ENGINE=InnoDB;

CREATE TABLE {$NAMESPACE}_user.organization_operation (
  operationID VARBINARY(128) NOT NULL PRIMARY KEY,
  actorPHID VARBINARY(64) NOT NULL,
  requestDigest VARBINARY(64) NOT NULL,
  resultJSON LONGTEXT NOT NULL,
  createdAt BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE {$NAMESPACE}_user.organization_audit (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  operationID VARBINARY(128) NOT NULL,
  actorPHID VARBINARY(64) NOT NULL,
  action VARBINARY(32) NOT NULL,
  unitID VARBINARY(64) NOT NULL,
  subjectPHID VARBINARY(64) DEFAULT NULL,
  beforeJSON LONGTEXT NOT NULL,
  afterJSON LONGTEXT NOT NULL,
  createdAt BIGINT UNSIGNED NOT NULL,
  KEY key_operation (operationID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE {$NAMESPACE}_user.organization_approval (
  approvalID VARBINARY(128) NOT NULL PRIMARY KEY,
  operationID VARBINARY(128) NOT NULL,
  requestDigest VARBINARY(64) NOT NULL,
  bindingJSON LONGTEXT NOT NULL,
  state VARBINARY(16) NOT NULL,
  approverPHID VARBINARY(64) DEFAULT NULL,
  approverVersion BIGINT UNSIGNED DEFAULT NULL,
  approverDigest VARBINARY(64) DEFAULT NULL,
  approverBindingJSON LONGTEXT DEFAULT NULL,
  approvedAt BIGINT UNSIGNED DEFAULT NULL,
  consumedAt BIGINT UNSIGNED DEFAULT NULL,
  consumedByOperation VARBINARY(128) DEFAULT NULL,
  version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  KEY key_operation (operationID),
  KEY key_consumed (consumedByOperation)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
